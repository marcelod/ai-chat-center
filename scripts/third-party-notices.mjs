// Generates plugin/THIRD-PARTY-NOTICES.md from package metadata (called by scripts/build.mjs).
// Covered: the runtime dependencies bundled into the web UI (react, react-dom, react-markdown,
// remark-gfm and everything they depend on), the bundled fonts (@fontsource, OFL-1.1) and the
// Tailwind CSS base styles compiled into the stylesheet, and @xterm/headless, bundled into the hub (it plays
// the session screen, spec 2026-11-27-session-screen-terminal). The hook and waiter bundles use only Node
// built-ins. Type-only packages (@types/*) are skipped: nothing of them is shipped.
import fs from 'node:fs';
import path from 'node:path';

const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt', 'license', 'license.md', 'LICENCE', 'LICENCE.md', 'OFL.txt'];
const EXTRA = ['@fontsource/inter', '@fontsource/jetbrains-mono', '@fontsource/space-grotesk', 'tailwindcss'];
/** Bundled into plugin/dist/hub.mjs. */
const HUB = ['@xterm/headless'];

function resolvePkg(name, fromDir, root) {
  // Node resolution: walk up from the requiring package to the root node_modules.
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name, 'package.json');
    if (fs.existsSync(candidate)) return path.dirname(candidate);
    if (dir === root || path.dirname(dir) === dir) break;
  }
  const top = path.join(root, 'node_modules', name);
  return fs.existsSync(path.join(top, 'package.json')) ? top : null;
}

export function collectPackages(root) {
  const ui = JSON.parse(fs.readFileSync(path.join(root, 'ui', 'package.json'), 'utf8'));
  const found = new Map(); // name@version -> {name, version, license, dir}
  const queue = [...[...Object.keys(ui.dependencies ?? {}), ...EXTRA].map((name) => [name, path.join(root, 'ui')]), ...HUB.map((name) => [name, root])];
  while (queue.length) {
    const [name, from] = queue.shift();
    if (name.startsWith('@types/')) continue;
    const dir = resolvePkg(name, from, root);
    if (!dir) throw new Error(`third-party notices: cannot resolve ${name}`);
    const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const id = `${pkg.name}@${pkg.version}`;
    if (found.has(id)) continue;
    const license = typeof pkg.license === 'string' ? pkg.license : (pkg.license?.type ?? 'UNKNOWN');
    found.set(id, { name: pkg.name, version: pkg.version, license, dir });
    for (const dep of Object.keys(pkg.dependencies ?? {})) queue.push([dep, dir]);
  }
  return [...found.values()].sort((a, b) => (a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name)));
}

export function renderNotices(root) {
  const pkgs = collectPackages(root);
  const out = [
    '# Third-party notices',
    '',
    'AI Chat Center bundles the following third-party software in `plugin/dist/ui` (the web UI and its fonts) and `plugin/dist/hub.mjs` (@xterm/headless).',
    'This file is generated by `scripts/third-party-notices.mjs` during `npm run build`; do not edit it by hand.',
    '',
    '| Package | Version | License |',
    '|---|---|---|',
    ...pkgs.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    '',
  ];
  for (const p of pkgs) {
    out.push(`## ${p.name}@${p.version} (${p.license})`, '');
    const file = LICENSE_FILES.map((f) => path.join(p.dir, f)).find((f) => fs.existsSync(f));
    if (file) {
      const text = fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n').trim();
      out.push('```text', text.replace(/```/g, "'''"), '```', '');
    } else {
      out.push(`No license file is included in the package; its package.json declares ${p.license}.`, '');
    }
  }
  return out.join('\n');
}
